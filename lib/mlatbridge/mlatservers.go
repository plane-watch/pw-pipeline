package mlatbridge

import (
	"slices"
)

func MLATServer(fid int) string {
	for region, rfids := range MLATRegionByFID {
		if slices.Contains(rfids, fid) {
			return MLATServers[region]
		}
	}
	return MLATServers[Unknown]
}

func GetMLATRegionByFID(fid int) MLATRegion {
	for region, rfids := range MLATRegionByFID {
		if slices.Contains(rfids, fid) {
			return region
		}
	}
	return Unknown
}

